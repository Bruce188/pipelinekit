#!/usr/bin/env bash
# Tests claude/git-hooks/{commit-msg,pre-commit,pre-push} against throwaway
# repos that point core.hooksPath at the kit's git-hooks directory.
set -uo pipefail

KIT_HOOKS="$(cd "$(dirname "$0")/../../git-hooks" && pwd)"
TMP=$(mktemp -d "${TMPDIR:-/tmp}/pkit-githooks-XXXXXX")
trap 'rm -rf "$TMP"' EXIT
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1
export GIT_AUTHOR_NAME=t GIT_AUTHOR_EMAIL=t@e GIT_COMMITTER_NAME=t GIT_COMMITTER_EMAIL=t@e
unset ALLOW_MAIN_PUSH PIPELINEKIT_ALLOW_SECRET

PASS=0 FAIL=0
check() { # check <name> <expected: ok|fail> <command...>
  local name=$1 want=$2 got=ok; shift 2
  "$@" >"$TMP/out" 2>&1 || got=fail; cp "$TMP/out" "$TMP/last"
  if [ "$got" = "$want" ]; then PASS=$((PASS + 1)); else
    FAIL=$((FAIL + 1)); echo "FAIL: $name (wanted $want)"; sed 's/^/    /' "$TMP/out"; fi
}

mkrepo() {
  git init -q -b feat "$1"
  git -C "$1" config core.hooksPath "$KIT_HOOKS"
}

commit() { # commit <repo> <message>
  date +%s%N >>"$1/f.txt"
  git -C "$1" add f.txt && git -C "$1" commit -q -m "$2"
}

# ---------------- commit-msg
R="$TMP/repo"; mkrepo "$R"
for m in "feat: add x" "fix: x" "feat(api)!: drop v1" "fix(ui/nav): y" "revert: undo x" \
         "fix: handle stream a/b split" "docs: 3 findings from audit" "chore: tune WIP limits" \
         "refactor!: rename" $'feat: x\n\nCo-Authored-By: Jane <jane@example.com>' \
         $'test: y\n\n- [x] done ✓' "Merge branch 'x' into feat" 'Revert "feat: add x"' \
         "fixup! feat: add x" "squash! feat: add x"; do
  check "accept: ${m%%$'\n'*}" ok commit "$R" "$m"
done
for m in "WIP" "wip: stuff" "feat: wip" "update stuff" "feat:missing space" "Feat: x" "feature: x" \
         "feat: $(printf 'a%.0s' {1..100})" $'feat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>' \
         $'feat: x\n\n\U0001F916 Generated with Claude Code' $'feat: x\n\nGenerated by ChatGPT' \
         $'feat: add sparkle ✨' $'fix: y \U0001F680'; do
  check "reject: ${m%%$'\n'*}" fail commit "$R" "$m"
done

W="$TMP/home/.claude/worktrees/agent1"; mkdir -p "$(dirname "$W")"; mkrepo "$W"
check "worktree allows wip" ok commit "$W" "wip: checkpoint"
check "worktree still rejects AI trailer" fail commit "$W" $'wip: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>'

# chaining: repo-local hooks run after the global checks
printf '#!/bin/sh\necho local-ran >>"%s/chain.log"\n' "$TMP" >"$R/.git/hooks/commit-msg"
chmod +x "$R/.git/hooks/commit-msg"
check "chains to .git/hooks/commit-msg" ok commit "$R" "feat: chained"
check "chain ran" ok grep -q local-ran "$TMP/chain.log"
printf '#!/bin/sh\necho "local says no" >&2; exit 1\n' >"$R/.git/hooks/commit-msg"
check "local commit-msg can veto" fail commit "$R" "feat: vetoed"
rm "$R/.git/hooks/commit-msg"
mkdir -p "$R/.githooks"
printf '#!/bin/sh\nexit 1\n' >"$R/.githooks/commit-msg"; chmod +x "$R/.githooks/commit-msg"
check "chains to .githooks/commit-msg" fail commit "$R" "feat: vetoed by githooks"
rm -r "$R/.githooks"
ln -s "$KIT_HOOKS/commit-msg" "$R/.git/hooks/commit-msg"
check "no self-recursion via symlink" ok commit "$R" "feat: self link"
rm "$R/.git/hooks/commit-msg"

# ---------------- pre-commit (gitleaks stubbed so the argv is checked)
STUB="$TMP/stub"; mkdir -p "$STUB"
cat >"$STUB/gitleaks" <<EOF
#!/bin/sh
if [ "\$1" = version ]; then echo "\${STUB_VERSION:-8.24.2}"; exit 0; fi
echo "\$*" >>"$TMP/gitleaks.argv"
exit "\${STUB_EXIT:-0}"
EOF
chmod +x "$STUB/gitleaks"

if ! command -v gitleaks >/dev/null 2>&1; then
  check "gitleaks missing: allow" ok commit "$R" "feat: no scanner"
  check "gitleaks missing: warns" ok grep -q "gitleaks not installed" "$TMP/last"
fi
# Run the stubbed cases through a helper so PATH and STUB_* reach the hook.
cat >"$TMP/fns" <<'EOF'
date +%s%N >>"$1/f.txt"; git -C "$1" add f.txt && git -C "$1" commit -q -m "$2"
EOF
stubbed() { env PATH="$STUB:$PATH" "$@" bash "$TMP/fns" "$R" "feat: scan"; }
: >"$TMP/gitleaks.argv"
check "8.19+: clean allows" ok stubbed
check "8.19+: uses gitleaks git --staged" ok grep -q '^git --staged --redact --no-banner --exit-code 3' "$TMP/gitleaks.argv"
: >"$TMP/gitleaks.argv"
check "<8.19: clean allows" ok stubbed STUB_VERSION=v8.18.4
check "<8.19: uses gitleaks protect --staged" ok grep -q '^protect --staged' "$TMP/gitleaks.argv"
check "finding blocks" fail stubbed STUB_EXIT=3
check "gitleaks error blocks" fail stubbed STUB_EXIT=1
: >"$TMP/gitleaks.argv"
check "PIPELINEKIT_ALLOW_SECRET=1 skips" ok stubbed STUB_EXIT=3 PIPELINEKIT_ALLOW_SECRET=1
check "opt-out never calls gitleaks" fail test -s "$TMP/gitleaks.argv"
printf '#!/bin/sh\nexit 1\n' >"$R/.git/hooks/pre-commit"; chmod +x "$R/.git/hooks/pre-commit"
check "chains to .git/hooks/pre-commit" fail stubbed
rm "$R/.git/hooks/pre-commit"

# ---------------- pre-push
git init -q --bare "$TMP/origin.git"
git -C "$R" remote add origin "$TMP/origin.git"
check "push feature branch" ok git -C "$R" push -q origin feat
check "push feat:main refused" fail git -C "$R" push -q origin feat:main
check "push HEAD:refs/heads/master refused" fail git -C "$R" push -q origin HEAD:refs/heads/master
git -C "$R" branch -q main
check "push main refused" fail git -C "$R" push -q origin main
check "push +main refused" fail git -C "$R" push -q origin +main
check "push --all refused" fail git -C "$R" push -q --all origin
check "ALLOW_MAIN_PUSH=1 allows" ok env ALLOW_MAIN_PUSH=1 git -C "$R" push -q origin main
check "deleting a branch allowed" ok git -C "$R" push -q origin :feat
cat >"$R/.git/hooks/pre-push" <<EOF
#!/bin/sh
cat >"$TMP/prepush.stdin"
EOF
chmod +x "$R/.git/hooks/pre-push"
check "chains to .git/hooks/pre-push" ok git -C "$R" push -q origin feat
check "chained hook gets the refs on stdin" ok grep -q '^refs/heads/feat [0-9a-f]* refs/heads/feat ' "$TMP/prepush.stdin"

echo "Results: $PASS PASS / $FAIL FAIL"
[ "$FAIL" -eq 0 ]
